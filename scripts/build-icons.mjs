#!/usr/bin/env node
/*
 * Regenerate assets/js/icons.js: the subset of Lucide icons the site uses.
 *
 *   npm i --no-save lucide-static@0.453.0
 *   node scripts/build-icons.mjs [path/to/lucide-static/icons]
 *
 * Keeps every icon already in icons.js (UI icons used by code) and adds any
 * icon named in assets/js/registry.js (tools and categories) or passed with
 * --add name1,name2.
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const addIdx = args.indexOf('--add');
const extra = addIdx >= 0 ? args.splice(addIdx, 2)[1].split(',').filter(Boolean) : [];
const dir = args[0] || path.join(ROOT, 'node_modules/lucide-static/icons');
if (!fs.existsSync(dir)) { console.error(`Lucide icons not found at ${dir}`); process.exit(1); }

const OUT = path.join(ROOT, 'assets/js/icons.js');
const current = fs.existsSync(OUT) ? require(OUT) : {};
const { TOOLS, CATEGORIES } = require(path.join(ROOT, 'assets/js/registry.js'));
const names = new Set([...Object.keys(current), ...TOOLS.map((t) => t.icon), ...CATEGORIES.map((c) => c.icon), ...extra]);

const out = {}, missing = [];
for (const n of [...names].sort()) {
  const f = path.join(dir, `${n}.svg`);
  if (!fs.existsSync(f)) { if (current[n]) out[n] = current[n]; else missing.push(n); continue; }
  out[n] = fs.readFileSync(f, 'utf8').replace(/<!--.*?-->/s, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s*\n\s*/g, '');
}
fs.writeFileSync(OUT, '/* Lucide icons v0.453.0 (ISC licence, https://lucide.dev). Generated by scripts/build-icons.mjs. */\n' +
  '(function(root){var ICONS=' + JSON.stringify(out) + ';\nif(typeof module!=="undefined"&&module.exports)module.exports=ICONS;else root.BT_ICONS=ICONS;})(this);\n');
console.log(`${Object.keys(out).length} icons written${missing.length ? `; missing: ${missing.join(', ')}` : ''}`);
